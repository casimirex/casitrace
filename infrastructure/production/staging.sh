#!/usr/bin/env bash
# Local staging rehearsal of the production deployment (P9): production images, production
# configuration (NODE_ENV=production, KMS signer, AppRole, metrics token, Caddy in front), with local
# stand-ins for the external services (compose.staging.yml).
#
#   infrastructure/production/staging.sh up        build, start, bootstrap the KMS on first run
#   infrastructure/production/staging.sh unseal    unseal the KMS after a restart
#   infrastructure/production/staging.sh down      stop (keeps volumes)
#   infrastructure/production/staging.sh destroy   stop and delete all staging data
set -euo pipefail
cd "$(dirname "$0")"
ENV_FILE=.env.staging
DC=(docker compose -p casitrace-staging -f compose.yml -f compose.staging.yml --env-file "$ENV_FILE")
rand() { openssl rand -hex "${1:-32}"; }

ensure_env() {
  [ -f "$ENV_FILE" ] && return
  cat > "$ENV_FILE" <<EOF
# Generated by staging.sh — local rehearsal only.
SITE_ADDRESS=:8080
PUBLIC_PORT=8080
WEB_ORIGIN=http://localhost:8080
PUBLIC_ORIGIN=http://localhost:8080
AUTH_SECRET=$(rand)
DB_OWNER_PASSWORD=$(rand 16)
APP_DB_PASSWORD=$(rand 16)
METRICS_TOKEN=$(rand)
S3_ENDPOINT=http://s3:8333
S3_REGION=us-east-1
S3_BUCKET=casitrace-evidence
S3_ACCESS_KEY_ID=casitrace
S3_SECRET_ACCESS_KEY=casitrace-dev-secret
BACKUP_S3_ENDPOINT=http://s3:8333
BACKUP_S3_REGION=us-east-1
BACKUP_S3_PREFIX=s3://casitrace-backups/pg
BACKUP_S3_ACCESS_KEY_ID=casitrace
BACKUP_S3_SECRET_ACCESS_KEY=casitrace-dev-secret
BACKUP_ENCRYPTION_KEY=$(rand)
SMTP_HOST=mailpit
SMTP_PORT=1025
MAIL_FROM="Casitrace Staging <no-reply@staging.local>"
ALERT_FROM=alerts@staging.local
ALERT_SMTP_REQUIRE_TLS=false
ALERT_ONCALL_EMAIL=oncall@staging.local
ALERT_TICKETS_EMAIL=tickets@staging.local
KMS_ROLE_ID=
KMS_SECRET_ID=
EOF
  echo "wrote $ENV_FILE"
}

render_monitoring() (
  # Subshell: exported values must not leak into later compose calls (shell env beats --env-file).
  set -a; . "./$ENV_FILE"; set +a
  printf '%s' "$METRICS_TOKEN" > monitoring/metrics-token
  chmod 644 monitoring/metrics-token
  SMTP_USER=${SMTP_USER:-} SMTP_PASSWORD=${SMTP_PASSWORD:-} envsubst < monitoring/alertmanager.yml.tmpl > monitoring/alertmanager.yml
)

set_env() { # set_env KEY VALUE
  if grep -q "^$1=" "$ENV_FILE"; then sed -i "s#^$1=.*#$1=$2#" "$ENV_FILE"; else echo "$1=$2" >> "$ENV_FILE"; fi
}

unseal() {
  local key
  key=$(grep '^STAGING_UNSEAL_KEY=' "$ENV_FILE" | cut -d= -f2-)
  "${DC[@]}" exec -T openbao bao operator unseal -address=http://127.0.0.1:8200 "$key" >/dev/null
  echo "KMS unsealed"
}

bootstrap_kms() {
  "${DC[@]}" up -d openbao
  for _ in $(seq 1 60); do
    "${DC[@]}" exec -T openbao wget -q -O /dev/null "http://127.0.0.1:8200/v1/sys/health?uninitcode=200&sealedcode=200" 2>/dev/null && break
    sleep 1
  done
  if grep -q '^KMS_ROLE_ID=.\+' "$ENV_FILE"; then
    unseal
    return
  fi
  # Staging: one key share, kept in the env file so the rehearsal can restart. Production uses 5/3
  # with offline custodians (runbook).
  local out
  # Also kept in a git-ignored file, so a failed bootstrap does not lose the unseal key (staging only).
  out=$("${DC[@]}" exec -T -e SHARES=1 -e THRESHOLD=1 openbao sh /openbao/kms/bootstrap.sh | tee .kms-bootstrap.staging.log)
  set_env STAGING_UNSEAL_KEY "$(echo "$out" | sed -n 's/^UNSEAL_KEY_1=//p')"
  set_env KMS_ROLE_ID "$(echo "$out" | sed -n 's/^KMS_ROLE_ID=//p')"
  set_env KMS_SECRET_ID "$(echo "$out" | sed -n 's/^KMS_SECRET_ID=//p')"
  set_env STAGING_KEY_OPERATOR_TOKEN "$(echo "$out" | sed -n 's/^KEY_OPERATOR_TOKEN=//p')"
  echo "KMS bootstrapped (root token revoked)"
}

case "${1:-up}" in
  up)
    ensure_env
    render_monitoring
    "${DC[@]}" build
    bootstrap_kms
    "${DC[@]}" up -d --wait --wait-timeout 300 web api worker prometheus alertmanager otel mailpit backup clamav evidence-mirror
    "${DC[@]}" ps --format 'table {{.Service}}\t{{.Status}}'
    echo "staging: http://localhost:8080  (mail :8026, grafana :3001, prometheus :9090)"
    ;;
  unseal) unseal ;;
  down) "${DC[@]}" down ;;
  destroy) "${DC[@]}" down -v; rm -f "$ENV_FILE" monitoring/alertmanager.yml monitoring/metrics-token ;;
  dc) shift; "${DC[@]}" "$@" ;;
  *) echo "usage: $0 up|unseal|down|destroy|dc <compose args>" >&2; exit 2 ;;
esac
